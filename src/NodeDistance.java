public class NodeDistance {
    private int node;
    private int distance;

    public NodeDistance(int node, int distance) {
        this.node = node;
        this.distance = distance;
    }

    public int getNode() {
        return node;
    }

    public int getDistance() {
        return distance;
    }

    public void setNode(int node) {
        this.node = node;
    }

    public void setDistance(int distance) {
        this.distance = distance;
    }
}